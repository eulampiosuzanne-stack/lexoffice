import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const code=ts.transpileModule(fs.readFileSync('src/lib/clientAppInbox.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {inboxMatches,inboxSubject,inboxKind}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const rows=[{id:'a',client_id:'c',clients:{name:'João Silva'},subject:'Autorização',body:'Contrato disponível',read_at:null,kind:'document'},{id:'b',client_id:'d',subject:'Pagamento',body:'Comprovante de depósito',read_at:'2026-10-22',kind:'payment_receipt'},{id:'c',client_id:'e',body:null,subject:null}];
const filter=(type,query='')=>rows.filter(row=>inboxMatches(row,type,query)).map(row=>row.id);
assert.deepEqual(filter('all'),['a','b','c']);
assert.deepEqual(filter('unread'),['a','c']);
assert.deepEqual(filter('document','  JOAO  '),['a']);
assert.deepEqual(filter('all','autorizacao'),['a']);
assert.deepEqual(filter('payment_receipt','deposito'),['b']);
assert.deepEqual(filter('document','deposito'),[]);
assert.deepEqual(filter('all','inexistente'),[]);
assert.equal(inboxSubject(rows[2]),'Nova mensagem');
assert.equal(inboxSubject({...rows[0],subject:null}),'Documento enviado');
assert.equal(inboxKind(rows[1]),'Comprovante');
assert.deepEqual(filter('unread','pagamento'),[]);
console.log('PASS client app inbox: accent-insensitive client/subject/body search, unread versus read, document/payment filters, combined search and safe empty fields.');
