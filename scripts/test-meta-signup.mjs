import assert from 'node:assert/strict';
import { signupAssets, validMetaConnection } from '../src/lib/metaSignup.ts';
import { requireAssets, assertToken, selectPhone } from '../supabase/functions/meta-whatsapp-oauth/validation.ts';
const event = { type: 'WA_EMBEDDED_SIGNUP', event: 'FINISH', data: {waba_id:'100',phone_number_id:'200'} };
assert.deepEqual(signupAssets('https://www.facebook.com', JSON.stringify(event)), event.data);
assert.equal(signupAssets('https://www.facebook.com.evil.test',event),null);
assert.equal(signupAssets('https://evil.test',event),null);
assert.equal(signupAssets('https://www.facebook.com','broken'),null);
assert.equal(signupAssets('https://www.facebook.com',{...event,event:'CANCEL'}),null);
assert.equal(signupAssets('https://www.facebook.com',{...event,data:{waba_id:'100'}}),null);
assert.equal(validMetaConnection({status:'connected',settings:{}}),false);
assert.equal(validMetaConnection({status:'connecting',settings:event.data}),false);
assert.equal(validMetaConnection({status:'connected',settings:event.data}),true);
assert.throws(()=>requireAssets({waba_id:'100'}));
const token={is_valid:true,app_id:'300',scopes:['whatsapp_business_management','whatsapp_business_messaging'],granular_scopes:[{scope:'whatsapp_business_management',target_ids:['100']}]};
assert.doesNotThrow(()=>assertToken(token,'300','100'));
assert.throws(()=>assertToken({...token,is_valid:false},'300','100'));
assert.throws(()=>assertToken(token,'301','100'));
assert.throws(()=>assertToken(token,'300','101'));
assert.throws(()=>assertToken({...token,scopes:[]},'300','100'));
assert.throws(()=>assertToken({...token,granular_scopes:[]},'300','100'));
assert.equal(selectPhone([{id:'201',display_phone_number:'other'},{id:'200',display_phone_number:'selected'}],'200').display_phone_number,'selected');
assert.throws(()=>selectPhone([{id:'201',display_phone_number:'other'}],'200'));
console.log('Meta signup: 19 assertions passed.');
