import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const service=read('src/pages/Service.tsx');
const main=read('src/main.tsx');
const inbox=read('src/pages/service-workspace.css');
const tokens=read('src/design-system/tokens.css');
const bulk=read('src/pages/service-bulk.css');
assert(!service.includes('const css=\x60'),'Legacy inline Service CSS must stay removed');
assert(!service.includes('service-2.css'),'Legacy override stack must stay retired');
assert(!service.includes('<style>'),'Inbox should not inject runtime CSS');
assert(service.includes('service-shell')&&service.includes('details-collapsed')&&service.includes('has-selection'));
assert(service.includes('service-details')&&service.includes('service-compose')&&service.includes('bulk-backdrop'));
assert(tokens.includes('html[data-lex-theme="light"]')&&tokens.includes('html[data-lex-theme="dark"]'));
for(const token of ['--lx-surface','--lx-text','--lx-primary','--lx-border'])assert(tokens.includes(token));
assert(inbox.includes('.service-shell.details-collapsed')&&inbox.includes('.service-shell:not(.has-selection)'));
assert(inbox.includes('@media(max-width:760px)')&&inbox.includes('@media(max-width:1050px)'));
assert(inbox.includes('.service-bubble.out')&&inbox.includes('.service-details'));
assert(!inbox.includes('!important'),'New Inbox CSS must not accumulate specificity patches');
assert(!bulk.includes('.service-chat-page \n.service-chat-page'));
assert(!fs.existsSync('src/pages/service-2.css'),'Retired legacy CSS must be deleted');
const imports=['./design-system/tokens.css','./design-system/components.css','./pages/service-workspace.css','./pages/service-bulk.css'];
for(const path of imports)assert(main.includes(path),'Missing CSS import: '+path);
assert(imports.every((p,i)=>i===0||main.indexOf(imports[i-1])<main.indexOf(p)),'Design system import order is unstable');
console.log('Design system and Inbox structural regression checks passed.');
